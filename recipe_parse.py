# 레시피 원문의 **소제목**이 첫 재료에 붙어 남는다 — "[재료] 굴 50g" 이
# '재료 굴' 이 되는 식이다. 자료 100건에서 56종이었고, 상점에서 '재료 굴' 을
# 찾으니 "구할 곳 없음" 이 됐다. 소제목 한 단어(…재료·…양념·…육수·…소스
# ·고명·드레싱·반죽·완자, …용) 뒤에 이름이 이어질 때만 뗀다.

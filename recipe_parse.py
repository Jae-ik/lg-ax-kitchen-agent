def expand_avoid(avoid) -> tuple[list[str], list[str], list[str]]:
    """기피 목록의 범주어를 구체 재료로 푼다.

    돌려주는 것: (풀린 목록, 무엇을 풀었는지, **풀지 못한 범주어**)
    풀지 못한 것은 그대로 남긴다(글자가 원문에 있으면 걸리므로). 다만
    그것만으로는 거의 아무것도 안 걸러지므로 호출자가 멈춰야 한다.
    """
    out, notes, unresolved = [], [], []
    for a in avoid or []:
        a = (a or "").strip()
        if not a:
            continue
        if a in CATEGORY:
            parts = CATEGORY[a]
            notes.append(f"{a} → {', '.join(parts)}")
            out.extend(parts)
        elif a in DERIVED:
            parts = DERIVED[a]
            notes.append(f"{a} 와 그것으로 만든 것 → {', '.join(parts)} "
                         f"(대표 성분 기준 — 실제 제품은 성분표를 본다)")
            out.extend(parts)
        else:
            if a.endswith("류") or a in ("해산물", "해물"):
                unresolved.append(a)
        if a not in out:
            out.append(a)
    seen = set()
    uniq = [x for x in out if not (x in seen or seen.add(x))]
    return uniq, notes, unresolved


def _is_same_thing(keyword: str, name: str) -> bool:
    """기피어가 이 재료명을 가리키는가.

    같은 이름이면 같다. 알려진 '다른 것' 이거나 그것을 품고 있으면
    (양배추김치 ⊃ 배추) 다른 것이다. 그 밖에는 **같다고 본다** —
    모르는 것을 통과시키지 않는 쪽이 안전하다.
    """
    if name == keyword:
        return True
    exempt, _ = NOT_THE_SAME.get(keyword, (set(), ""))
    return not any(e in name for e in exempt)


def contains_any(text: str, keywords) -> list[str]:
    """재료 원문에 기피·알레르기 키워드가 들어 있는지 본다.

    구조화된 재료 목록이 아니라 **원문 전체**를 본다.
    파싱이 놓친 항목(5장·1뿌리처럼 g 표기가 없는 것)에도 알레르기 재료가
    있을 수 있는데, 안전 판정에서 그것을 놓치면 안 되기 때문이다.
    """
    t = text or ""
    out = []
    for k in keywords:
        if k not in t:
            continue
        # **어느 재료에 걸렸는지 함께 적는다.**
        #
        # 짧은 기피어는 다른 재료에 부분 일치한다 — 자료 100건에서
        #   배 → 배추(3)·양배추(2)·적양배추(1)
        #   게 → 스파게티(1)      밀 → 코코넛밀크(1)      파 → 파프리카(2)
        # 안전 판정이므로 **거르는 것 자체는 그대로 둔다**(놓치는 쪽이
        # 훨씬 위험하다). 다만 사용자가 "양배추감자전이 왜 빠졌지" 를
        # 알 수 없으면 그 판단을 검토할 수 없다. 걸린 재료를 적어 둔다.
        # **파싱 결과가 아니라 원문의 한글 덩어리로 본다.**
        # 'g' 표기가 없는 항목(배추 5장)은 파싱이 못 뽑으므로, 파싱에만
        # 기대면 그런 줄에서는 판단할 근거가 없어 무조건 걸러야 했다.
        # 덩어리로 보면 '배추' 를 직접 읽어 배와 다른 것임을 안다.
        chunks = [c for c in re.findall(r"[가-힣]+", t) if k in c]
        real = [c for c in chunks if _is_same_thing(k, c)]
        if chunks and not real:
            continue                            # 전부 다른 것이었다
        if not chunks:
            # 한글 덩어리로는 안 잡히는데 원문에는 있다(영문·숫자 섞임 등).
            # 판단할 근거가 없으므로 안전측으로 거른다.
            out.append(k)
            continue
        if any(c == k for c in real):
            out.append(k)                       # 정확히 그 재료다
        else:
            out.append(f"{k}({'·'.join(sorted(set(real))[:3])})")
    return out

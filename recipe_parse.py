# -*- coding: utf-8 -*-
"""식약처 조리식품 레시피 DB(COOKRCP01)의 재료 문자열을 구조화한다.

원문은 사람이 읽으라고 쓴 문장이라 표기가 두 가지로 섞여 있다.

    연두부 75g(3/4모), 칵테일새우 20g(5마리)     ← 이름 뒤에 수량
    돼지고기(50g), 배춧잎(5장), 부추(30g)        ← 괄호 안에 수량
    닭고기(가슴살, 120g)                          ← 괄호 안에 설명과 수량

둘 다 처리한다. g 단위가 없는 항목(5장·3알·1뿌리)은 버린다 —
질량으로 환산할 근거가 없는 값을 지어내지 않기 위해서다.
"""
from __future__ import annotations
import re

NAME = r"[가-힣A-Za-z][가-힣A-Za-z0-9 ]{0,12}?"

# 괄호 안에 수량:  돼지고기(50g) / 닭고기(가슴살, 120g)
P_PAREN = re.compile(rf"({NAME})\s*\(\s*(?:[^()]*?,\s*)?([\d]+(?:\.[\d]+)?)\s*g\s*[^()]*\)")
# 이름 뒤에 수량:  연두부 75g(3/4모)
P_PLAIN = re.compile(rf"({NAME})\s*([\d]+(?:\.[\d]+)?)\s*g")

# 재료명 앞에 붙는 조리 상태. 같은 재료를 다른 이름으로 세지 않기 위해 떼어낸다.
# 한 글자 접두어(간·생·건)는 **뒤에 공백이 있을 때만** 떼어낸다.
# 예전에는 공백 없이도 떼어내, 실제 자료 100건에서
#   간장 -> 장 (6회) · 생강 -> 강 (5회) · 생크림 -> 크림 (8회)
#   생강청 -> 강청 (3회) · 생강즙 -> 강즙 (2회)
# 가 됐다. '장' 은 재고의 '간장' 과 대조되지 않아 없는 재료로 잡힌다.
# 두 글자 이상 접두어는 붙여 쓰는 것이 보통이라 공백을 요구하지 않는다
# (저염간장 -> 간장 9회 · 다진마늘 -> 마늘 6회 · 저염된장 -> 된장 4회).
# 잃는 것은 '건새우 -> 새우' 3회뿐이고, 얻는 것이 24회다.
PREFIX = re.compile(
    r"^(?:(?:다진|저염|말린|삶은|불린|채썬|냉동|시판|무염)\s*|(?:간|생|건)\s+)")
# 이름 뒤에 남는 개수 표기. "달걀 1개 50g" 에서 이름이 '달걀 1개' 가 되면
# 재고의 '달걀' 과 대조되지 않아 없는 재료로 잡힌다.
# (실제 자료 100건·재료 1025개 중 2건: '달걀 1개', '오징어 1마리')
COUNT_SUFFIX = re.compile(
    r"\s*\d+(?:\.\d+)?\s*"
    r"(개|마리|장|알|쪽|톨|뿌리|줄기|컵|큰술|작은술|봉|팩|공기|인분|모|송이|단)?$")
JUNK = {"", "물", "약간", "적당량"}


def clean(name: str) -> str:
    name = PREFIX.sub("", name.strip()).strip()
    name = COUNT_SUFFIX.sub("", name).strip()
    return re.sub(r"\s+", " ", name)


def _split_items(text: str) -> list[str]:
    """쉼표·줄바꿈으로 나누되, 괄호 안의 쉼표는 자르지 않는다.

    '닭고기(가슴살, 120g)' 을 그냥 쉼표로 자르면 '닭고기(가슴살' 과 '120g)' 이
    되어 수량을 잃는다. 괄호 깊이를 세면서 나눈다.
    """
    items, buf, depth = [], [], 0
    for ch in text or "":
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth = max(0, depth - 1)
        if depth == 0 and (ch == "," or ch == "\n"):
            items.append("".join(buf)); buf = []
        else:
            buf.append(ch)
    items.append("".join(buf))
    return items


def parse_ingredients(text: str) -> list[dict]:
    """재료 문자열 → [{name, qty_g}] . 순서는 원문 순서를 지킨다."""
    out, seen = [], set()
    for seg in _split_items(text):
        seg = seg.strip().lstrip("●·•[]-—").strip()
        if not seg:
            continue
        m = P_PAREN.search(seg) or P_PLAIN.search(seg)
        if not m:
            continue
        name, qty = clean(m.group(1)), float(m.group(2))
        if name in JUNK or len(name) > 12:
            continue
        if name in seen:
            # 같은 재료가 두 번 나오면 **합친다.** 전에는 뒤엣것을 버려서
            # 양이 적게 계산됐다 (밑간용 간장 + 조림용 간장처럼 실제
            # 레시피에 흔하다. 자료 100건에서 11건).
            for o in out:
                if o["name"] == name:
                    o["qty_g"] = round(o["qty_g"] + qty, 2)
                    break
            continue
        seen.add(name)
        out.append({"name": name, "qty_g": qty})
    return out


# ── 기피어가 들어가도 **같은 것이 아닌** 재료 ─────────────────────────
#
# 판정은 원문을 부분 일치로 본다(파싱이 놓친 항목까지 잡으려고). 그런데
# 짧은 기피어는 관계없는 재료에 걸린다 — 배 알레르기인 사람이 배추를
# 못 먹게 되는 식이다.
#
# 그래서 **확실히 다른 것만** 여기에 적는다. 여기 없는 부분 일치는
# 계속 거른다 — 놓치는 쪽(미탐)이 훨씬 위험하기 때문이다.
# 애매한 것은 일부러 넣지 않았다:
#     무순   무의 싹이라 같을 수 있다
#     콩나물 대두에서 나온 것이므로 대두 알레르기면 걸러야 한다
#     건새우·새우젓·칵테일새우  전부 새우다
#
# 새 쌍을 넣을 때는 **식물학적·성분상 정말 다른지** 확인하고 근거를 적는다.
NOT_THE_SAME = {
    "배":  ({"배추", "양배추", "적양배추", "배춧잎", "얼갈이배추"},
            "배(과일)와 배추(십자화과 채소)는 다른 식물이다"),
    "게":  ({"스파게티", "얇게", "잘게", "굵게", "두껍게", "작게", "크게",
             "길게", "짧게", "넓게", "곱게", "가늘게", "납작하게", "좋게"},
            "스파게티는 음운이 겹칠 뿐이고, '얇게 썬' 의 '-게' 는 부사다 — "
            "범주어(갑각류)를 풀자 '얇게' 가 게로 걸렸다"),
    "밀":  ({"코코넛밀크", "밀크", "아몬드밀크", "우유밀크"},
            "'밀크'는 젖·식물성 음료이고 밀(곡물)이 아니다"),
    "파":  ({"파프리카", "파스타", "파인애플", "파슬리"},
            "대파·쪽파와 무관한 재료들이다"),
    "무":  ({"무화과", "무말랭이"},
            "무화과는 무와 무관하다. 무말랭이는 무이지만 건조품이라 "
            "표기가 다를 뿐이므로 제외하지 않는다 → 목록에서 뺀다"),
    "굴":  ({"굴소스"},
            "굴소스는 굴 성분을 담으므로 **제외하지 않는다** → 목록에서 뺀다"),
}
# 위 주석대로, 성분이 실제로 이어지는 것은 목록에서 뺀다.
NOT_THE_SAME["무"] = ({"무화과"}, "무화과는 무와 무관하다")
# 굴소스는 굴 성분이라 거른다. 굴비는 말린 조기라 굴과 무관하다 —
# 범주어(조개류)를 풀면 '굴' 이 들어오므로 이때 필요해졌다.
NOT_THE_SAME["굴"] = ({"굴비"}, "굴비는 말린 조기이고 굴(조개)이 아니다")


# ── 범주어를 구체 재료로 푼다 ──────────────────────────────────────────
#
# 사람은 "갑각류 못 먹어" 라고 말한다. 그런데 판정은 **문자열 일치**라
# '갑각류' 라는 글자는 "새우 50g" 에 없다. 실제로 LLM 이 '갑각류' 를
# 정확히 읽었는데 공개 자료 100건 중 갑각류가 든 15건이 **하나도 안
# 걸렀다.** 읽는 쪽이 옳아도 받는 쪽이 범주를 모르면 소용없다.
#
# 이 표는 **완전하지 않다.** 그래서 범주어를 풀었을 때도 사람 확인을
# 요청하고(thinq), 표에 없는 범주어('~류')가 오면 풀지 못했다고 알린다.
# 목록은 흔한 식재료 기준이며 식약처 알레르기 표시 대상과 대조가 필요하다.
CATEGORY = {
    "갑각류": ("새우", "게", "가재", "랍스터", "크랩", "크릴"),
    "조개류": ("조개", "굴", "전복", "홍합", "바지락", "가리비", "꼬막",
             "재첩", "백합", "소라", "키조개", "관자"),
    "견과류": ("호두", "아몬드", "잣", "캐슈넛", "피스타치오", "헤이즐넛",
             "마카다미아", "피칸", "땅콩"),     # 땅콩은 콩과지만 안전측으로 함께 본다
    "유제품": ("우유", "치즈", "버터", "생크림", "요거트", "요구르트", "연유",
             "분유"),
    "난류":   ("달걀", "계란", "메추리알", "마요네즈"),
    "생선류": ("멸치", "고등어", "연어", "참치", "명태", "북어", "황태", "동태",
             "대구", "갈치", "조기", "굴비", "꽁치", "삼치", "장어", "액젓",
             "어묵", "가자미", "광어"),
    "두족류": ("오징어", "문어", "낙지", "주꾸미", "쭈꾸미"),
}
CATEGORY["패류"] = CATEGORY["조개류"]
CATEGORY["알류"] = CATEGORY["난류"]
CATEGORY["우유류"] = CATEGORY["유제품"]
CATEGORY["해산물"] = (CATEGORY["갑각류"] + CATEGORY["조개류"]
                     + CATEGORY["생선류"] + CATEGORY["두족류"])
CATEGORY["해물"] = CATEGORY["해산물"]


def expand_avoid(avoid) -> tuple[list[str], list[str], list[str]]:
    """기피 목록의 범주어를 구체 재료로 푼다.

    돌려주는 것: (풀린 목록, 무엇을 풀었는지, **풀지 못한 범주어**)
    풀지 못한 것은 그대로 남긴다(글자가 원문에 있으면 걸리므로). 다만
    그것만으로는 거의 아무것도 안 걸러지므로 호출자가 멈춰야 한다.
    """
    out, notes, unresolved = [], [], []
    for a in avoid or []:
        a = (a or "").strip()
        if not a:
            continue
        if a in CATEGORY:
            parts = CATEGORY[a]
            notes.append(f"{a} → {', '.join(parts)}")
            out.extend(parts)
        else:
            if a.endswith("류") or a in ("해산물", "해물"):
                unresolved.append(a)
        if a not in out:
            out.append(a)
    seen = set()
    uniq = [x for x in out if not (x in seen or seen.add(x))]
    return uniq, notes, unresolved


def _is_same_thing(keyword: str, name: str) -> bool:
    """기피어가 이 재료명을 가리키는가.

    같은 이름이면 같다. 알려진 '다른 것' 이거나 그것을 품고 있으면
    (양배추김치 ⊃ 배추) 다른 것이다. 그 밖에는 **같다고 본다** —
    모르는 것을 통과시키지 않는 쪽이 안전하다.
    """
    if name == keyword:
        return True
    exempt, _ = NOT_THE_SAME.get(keyword, (set(), ""))
    return not any(e in name for e in exempt)


def contains_any(text: str, keywords) -> list[str]:
    """재료 원문에 기피·알레르기 키워드가 들어 있는지 본다.

    구조화된 재료 목록이 아니라 **원문 전체**를 본다.
    파싱이 놓친 항목(5장·1뿌리처럼 g 표기가 없는 것)에도 알레르기 재료가
    있을 수 있는데, 안전 판정에서 그것을 놓치면 안 되기 때문이다.
    """
    t = text or ""
    out = []
    for k in keywords:
        if k not in t:
            continue
        # **어느 재료에 걸렸는지 함께 적는다.**
        #
        # 짧은 기피어는 다른 재료에 부분 일치한다 — 자료 100건에서
        #   배 → 배추(3)·양배추(2)·적양배추(1)
        #   게 → 스파게티(1)      밀 → 코코넛밀크(1)      파 → 파프리카(2)
        # 안전 판정이므로 **거르는 것 자체는 그대로 둔다**(놓치는 쪽이
        # 훨씬 위험하다). 다만 사용자가 "양배추감자전이 왜 빠졌지" 를
        # 알 수 없으면 그 판단을 검토할 수 없다. 걸린 재료를 적어 둔다.
        # **파싱 결과가 아니라 원문의 한글 덩어리로 본다.**
        # 'g' 표기가 없는 항목(배추 5장)은 파싱이 못 뽑으므로, 파싱에만
        # 기대면 그런 줄에서는 판단할 근거가 없어 무조건 걸러야 했다.
        # 덩어리로 보면 '배추' 를 직접 읽어 배와 다른 것임을 안다.
        chunks = [c for c in re.findall(r"[가-힣]+", t) if k in c]
        real = [c for c in chunks if _is_same_thing(k, c)]
        if chunks and not real:
            continue                            # 전부 다른 것이었다
        if not chunks:
            # 한글 덩어리로는 안 잡히는데 원문에는 있다(영문·숫자 섞임 등).
            # 판단할 근거가 없으므로 안전측으로 거른다.
            out.append(k)
            continue
        if any(c == k for c in real):
            out.append(k)                       # 정확히 그 재료다
        else:
            out.append(f"{k}({'·'.join(sorted(set(real))[:3])})")
    return out
